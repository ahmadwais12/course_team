  static List<PageDefinition> getPagesForRole(String role) {
    return pages.where((p) => p.role == role || p.role == 'all').toList();
  }

  /// Get a page definition by ID
  static PageDefinition? getById(String id) {
    try {
      return pages.firstWhere((p) => p.id == id);
    } catch (_) {
      return null;
    }
