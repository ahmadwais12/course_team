/// Comprehensive mapping of all database tables to their corresponding
/// panel roles, icons, colors, and metadata.
/// This serves as the source of truth for page registration across all panels.
class PageDefinition {
  final String id;
  final String name;
  final String description;
  final String tableName;
  final String role;
  final String category;
  final IconData icon;
  final Color color;
  final String route;
  final String? orderBy;
  final List<String>? hiddenColumns;

  const PageDefinition({
    required this.id,
    required this.name,
    required this.description,
    required this.tableName,
    required this.role,
    required this.category,
    required this.icon,
    required this.color,
    required this.route,
    this.orderBy,
    this.hiddenColumns,
  });
}

